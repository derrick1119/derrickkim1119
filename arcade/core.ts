  /** 오너가 직접 준 아이디어로 만든 게임이면 그 출처 (계기판의 '오너 아이디어' 칸에 따로 보인다, 2026-11-08) */
  origin?: string;
  /** 시작 화면·접근성 문구에 쓸 조작 안내 (없으면 조작 종류별 기본 문구, 0023) */
  hint?: string;
