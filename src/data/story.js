export function bossPlay(key, hero) {
  const st = BOSS[key]; if (!st) return null;
  const list = st.play.slice(), own = st.hero[hero]; if (own) list.splice(list.length - 1, 0, own);
  return list.map(b => ({ bg: b.bg, s: b.s, a: b.a.map(a => (a[0] === 'H' ? [hero, ...a.slice(1)] : a)) }));
}

