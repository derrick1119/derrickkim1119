export type Kind = 'wood' | 'glass' | 'spring' | 'nail';
/** 판자 하나: 둥근 네모(가운데 cx,cy · 반폭 hx,hy · 각 a · 모서리 rr). sc = 나사 자리(작업판 좌표) */
export interface Src { cx: number; cy: number; hx: number; hy: number; a: number; rr: number; kind: Kind; tone: string; deco: string; sc: number[][]; lock?: number[]; key?: number; nail?: number[]; tgt?: number; tick?: number[][]; /** 🔨 망치 머리(정지 자세의 작업판 좌표) — 나사 하나에 매달리는 순간 그 근처 나사를 쾅 (M1′ S001, GIMMICKS §2) */ ham?: number[]; /** 🪵 통나무: 떨어지면 밑에 매달린 판자들을 위부터 쳐서 떨군다 (M1′ S002) */ heavy?: boolean; /** 실루엣 조각(🎨 ART M2 §1 · ✏️ S010): 'B x y hx hy r [deg]' · 'O x y r' · 'C x1 y1 x2 y2 t' · 'E x y a b [deg]' · 'W x1 y1 r1 x2 y2 r2' · 'P r x1 y1 x2 y2 …'를 ';'로 잇는다(u 정수 × 0.005 · 판자 로컬 = 가운데 0,0 · 각 a 기준).
   *  기본은 덧조각(본체 둥근 네모 + 조각, 무게중심 · 와르르 폭 = 본체 그대로 — M1′) · m2면 몸통 = 조각만 · 무게중심을 조각에서 */ parts?: string; m2?: boolean }
type O = Partial<Src>;
const mk = (cx: number, cy: number, hx: number, hy: number, a: number, rr: number, tone: string, sc: number[][], o: O = {}): Src => ({ cx, cy, hx, hy, a, rr: Math.min(rr, hx, hy), kind: 'wood', tone, deco: '', sc, ...o });
const bar = (x1: number, y1: number, x2: number, y2: number, t: number, tone: string, sc: number[][], o: O = {}) =>
  mk((x1 + x2) / 2, (y1 + y2) / 2, Math.hypot(x2 - x1, y2 - y1) / 2 + t, t, Math.atan2(y2 - y1, x2 - x1), t, tone, sc, o);
const plate = (cx: number, cy: number, w: number, h: number, a: number, rr: number, tone: string, sc: number[][], o: O = {}) => mk(cx, cy, w / 2, h / 2, a, rr, tone, sc, o);
const disc = (cx: number, cy: number, r: number, tone: string, sc: number[][], o: O = {}) => mk(cx, cy, r, r, 0, r, tone, sc, o);
/** 실루엣 덧조각(🎨 ART M2 §5 · ✏️ S010): 판자 번호 → 조각 문자열. 덮임 · 숨김 · 🔨 과녁 지문이 그대로인 바깥 가장자리만 · m2 = 몸통 바꿈(맨 밑 판자) */
const sil = (pl: Src[], m: Record<number, string>, m2: number[] = []) => (pl.forEach((p, k) => m[k] && ((p.parts = m[k]), m2.includes(k) && (p.m2 = true))), pl);

