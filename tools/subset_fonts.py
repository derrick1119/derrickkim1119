#!/usr/bin/env python3
"""Subset the two typefaces down to the characters the game actually uses.

Usage:  python3 tools/subset_fonts.py <NanumPenScript.ttf> <GowunBatang.ttf>

Reads every string in index.html and src/, keeps printable ASCII plus whatever
else appears there, and writes assets/fonts/fonts.css with both subsets inlined
as data: URIs (one small file, and it loads anywhere the page does).
Run it again whenever on-screen text changes. Needs: pip install fonttools brotli

It also writes assets/fonts/hand-letter.woff2: a much fuller cut of the hand
("TYT Letter": all 11,172 Hangul syllables, the jamo, ASCII and the punctuation
the face has) for the letter the player writes in the epilogue, which can hold
any word. The epilogue loads it only when it opens (src/scenes/letter.js).
"""
import base64
import io
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent


def used_chars():
    chars = {chr(c) for c in range(0x20, 0x7F)}
    files = [ROOT / "index.html", *sorted((ROOT / "src").rglob("*.js"))]
    for f in files:
        chars.update(ch for ch in f.read_text(encoding="utf-8") if ord(ch) > 0x7F)
    chars.update("…·「」“”‘’—–")
    return "".join(sorted(chars))


def make(src, text, family):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.notdef_outline = True
    font = TTFont(src)
    missing = sorted(ch for ch in text if ch.strip() and ord(ch) not in font.getBestCmap())
    sub = subset.Subsetter(opts)
    sub.populate(text=text)
    sub.subset(font)
    # A subset is a Modified Version under the OFL, so it must not carry a Reserved Font Name.
    for rec in font["name"].names:
        if rec.nameID in (1, 3, 4, 16):
            rec.string = family
        elif rec.nameID == 6:
            rec.string = family.replace(" ", "")
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()
    print(f"{family}: {len(data) / 1024:.1f} KB" + (f", not in this face: {' '.join(missing)}" if missing else ""))
    b64 = base64.b64encode(data).decode("ascii")
    return (
        f"@font-face {{ font-family: '{family}'; font-display: block; "
        f"src: url(data:font/woff2;base64,{b64}) format('woff2'); }}\n"
    )


def make_letter(src):
    """The hand for words the game cannot know in advance. No hinting: it is only ever drawn large.
    The source's own timestamp is kept, so the file comes out the same every time."""
    font = TTFont(src, recalcTimestamp=False)
    have = font.getBestCmap()
    keep = [c for c in have if 0x20 <= c < 0x7F or 0xAC00 <= c <= 0xD7A3 or 0x3131 <= c <= 0x318E
            or c in (0xA9, 0xB0, 0xD7, 0x2018, 0x2019, 0x201C, 0x201D, 0x20A9) or 0xFF01 <= c <= 0xFF5E]
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=keep)
    sub.subset(font)
    for rec in font["name"].names:   # a Modified Version: no Reserved Font Name
        if rec.nameID in (1, 3, 4, 16):
            rec.string = "TYT Letter"
        elif rec.nameID == 6:
            rec.string = "TYTLetter"
    font.flavor = "woff2"
    out = ROOT / "assets" / "fonts" / "hand-letter.woff2"
    font.save(out)
    print(f"TYT Letter: {out.stat().st_size / 1024:.1f} KB, {len(keep)} characters -> assets/fonts/hand-letter.woff2")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = used_chars()
    out = ROOT / "assets" / "fonts"
    out.mkdir(parents=True, exist_ok=True)
    css = (
        "/* Generated by tools/subset_fonts.py. Do not edit by hand.\n"
        "   TYT Hand is a subset of Nanum Pen Script; TYT Batang is a subset of Gowun Batang.\n"
        "   Both are under the SIL Open Font License 1.1; see the OFL-*.txt files beside this one. */\n"
    )
    css += make(sys.argv[1], text, "TYT Hand")
    css += make(sys.argv[2], text, "TYT Batang")
    (out / "fonts.css").write_text(css, encoding="utf-8")
    print(f"{len(text)} characters kept -> assets/fonts/fonts.css")
    make_letter(sys.argv[1])


if __name__ == "__main__":
    main()
