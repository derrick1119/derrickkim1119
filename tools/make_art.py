#!/usr/bin/env python3
"""Turn a piece of painted art into something the game can load.

Usage:  python3 tools/make_art.py <image> [name]

Crops away black letterbox bars (a phone screenshot of the art is fine), keeps a JPEG copy in
assets/art/<name>.jpg, and writes src/art.js, which holds every image in assets/art/ as a data URI
(so the single-file build carries the pictures too). The game reads them as T.art[name].
"""
import base64
import io
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = ROOT / "assets" / "art"


def crop_bars(im):
    g = im.convert("L")
    w, h = g.size
    px = g.load()
    def row_dark(y): return sum(px[x, y] for x in range(0, w, 4)) / len(range(0, w, 4)) < 10
    def col_dark(x): return sum(px[x, y] for y in range(0, h, 4)) / len(range(0, h, 4)) < 10
    top = next(y for y in range(h) if not row_dark(y))
    bot = next(y for y in range(h - 1, -1, -1) if not row_dark(y))
    left = next(x for x in range(w) if not col_dark(x))
    right = next(x for x in range(w - 1, -1, -1) if not col_dark(x))
    return im.crop((left, top + 1, right + 1, bot))


def main():
    if len(sys.argv) > 1:
        src = pathlib.Path(sys.argv[1])
        name = sys.argv[2] if len(sys.argv) > 2 else "key"
        im = crop_bars(Image.open(src).convert("RGB"))
        ART.mkdir(parents=True, exist_ok=True)
        im.save(ART / f"{name}.jpg", quality=92, optimize=True, progressive=True)
        print(f"{name}: {im.size[0]}x{im.size[1]} -> assets/art/{name}.jpg")
    lines = ["/* Generated by tools/make_art.py from assets/art/*.jpg. Do not edit by hand. */", "(function () {", "  'use strict';", "  const T = window.TYT;", "  T.art = {"]
    for f in sorted(ART.glob("*.jpg")):
        b = base64.b64encode(f.read_bytes()).decode("ascii")
        lines.append(f"    {f.stem!r}: 'data:image/jpeg;base64,{b}',".replace('"', "'"))
    lines += ["  };", "  /* decoded once, on first use */", "  const cache = {};",
              "  T.artImage = function (name) {",
              "    if (!T.art[name]) return null;",
              "    let im = cache[name];",
              "    if (!im) { im = cache[name] = new Image(); im.decoding = 'async'; im.src = T.art[name]; }",
              "    return im.complete && im.naturalWidth ? im : null;",
              "  };",
              "  Object.keys(T.art).forEach((n) => T.artImage(n));",
              "})();", ""]
    (ROOT / "src" / "art.js").write_text("\n".join(lines), encoding="utf-8")
    print(f"src/art.js: {(ROOT / 'src' / 'art.js').stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
